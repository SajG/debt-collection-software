// A very small .xlsx writer — enough for a formatted template with
// formulas, with no dependency. An .xlsx file is a ZIP of XML parts;
// the parts are stored uncompressed (they are a few KB).

export type Cell =
  | { t: "s"; v: string; style?: number }
  | { t: "n"; v: number; style?: number }
  | { t: "f"; v: string; style?: number }
  | null;

export type Sheet = { name: string; rows: Cell[][]; widths?: number[]; freezeTopRow?: boolean };

// Styles (index into cellXfs below).
export const STYLE = { normal: 0, header: 1, date: 2, money: 3, bold: 4, note: 5, moneyBold: 6 } as const;

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function colName(i: number): string {
  let s = "";
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

function sheetXml(sheet: Sheet): string {
  const cols = sheet.widths?.length
    ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join("")}</cols>`
    : "";
  const view = sheet.freezeTopRow
    ? `<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>`
    : "";
  const rows = sheet.rows
    .map((row, r) => {
      const cells = row
        .map((c, i) => {
          if (!c) return "";
          const ref = `${colName(i)}${r + 1}`;
          const s = c.style ? ` s="${c.style}"` : "";
          if (c.t === "s") return `<c r="${ref}" t="inlineStr"${s}><is><t xml:space="preserve">${esc(c.v)}</t></is></c>`;
          if (c.t === "n") return `<c r="${ref}"${s}><v>${c.v}</v></c>`;
          return `<c r="${ref}"${s}><f>${esc(c.v)}</f></c>`;
        })
        .join("");
      return cells ? `<row r="${r + 1}">${cells}</row>` : "";
    })
    .join("");
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${view}${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

